num1 = 5 
num2 = 2
print(num1+num2)  # 7
print(num1-num2)  # 3
print(num1*num2)  # 10
print(num1/num2)  # 2.5
print(num1//num2) # 2
print(num1%num2)  #1
print(num1**num2) # 25 '''sfsasfs'''
print(num1+num2,num1-num2,num1*num2,num1/num2,num1//num2,num1%num2,num1**num2)

print(f'sum :{num1+num2}\nsub : {num1-num2}\nmul : {num1*num2}')
